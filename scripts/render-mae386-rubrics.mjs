/** Rebuild the review copy from typed authoring data; no second answer key. */
import ts from "typescript";
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const temporary = mkdtempSync(join(tmpdir(), "sprout-mae386-review-"));
try {
  const directory = join(root, "lib/lesson-runtime/mae386");
  writeFileSync(join(temporary, "package.json"), '{"type":"commonjs"}');
  for (const file of readdirSync(directory).filter(file => file.endsWith(".ts"))) {
    const result = ts.transpileModule(readFileSync(join(directory, file), "utf8"), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    });
    writeFileSync(join(temporary, file.replace(/\.ts$/, ".js")), result.outputText);
  }
  const require = createRequire(join(temporary, "entry.js"));
  const { MAE386_RUBRICS, MAE386_ATTRIBUTION_RULES } = require("./rubrics.js");
  const { MANUSCRIPT_PASSAGES, MAE386_SOURCES } = require("./sources.js");
  const { MAE386_EXAM_SOURCE } = require("./exam-source.js");
  const lines = [
    "# MAE386 rubric review bundle",
    "",
    "Generated by `node scripts/render-mae386-rubrics.mjs` from typed content in `lib/lesson-runtime/mae386/`. Edit that content, then regenerate this review copy. This document is instructor-facing and must not be shown as a learner answer key.",
    "",
    "**Review status: awaiting user review.** This is commit 1 content, not a working voice demo. No microphone/provider acceptance has been performed. Fixture labels below are authored expectations, not measured Jev results or a validated grading benchmark. Implementation of Q10 latest-proposal selection, navigation intents and outcome snapshots remains for later commits.",
    "",
    "## Verified source identity and citation convention",
    "",
    `- Exam: [${MAE386_SOURCES.exam.identity}](sources/mae386/questions.pdf), ${MAE386_SOURCES.exam.pages} pages. Exam printed page numbers match one-based PDF viewer pages.`,
    `- Manuscript: [${MAE386_SOURCES.manuscript.identity}](sources/mae386/catchin-unicorns.pdf), ${MAE386_SOURCES.manuscript.pages} pages; PDF metadata creation ${MAE386_SOURCES.manuscript.pdfCreationDate}. Preface signature and metadata support the September 17, 2025 identity.`,
    `- Source inspection: ${MAE386_SOURCES.verifiedOn}. ${MAE386_SOURCES.pageConvention}`,
    "- Selected original question text below normalizes whitespace and line-wrap hyphenation. Original wording (including typos) is retained. Q5 has non-text figures: its cartoon on exam p. 5 and modern spindle image on p. 6 remain in the canonical PDF; they are not silently reconstructed as text.",
    "- Manuscript passages are summarized in our own words. Reference answers, probes and learner exemplars are authored for this demo, never attributed as quotations. Source claims have been checked against this manuscript, not independently established as universal scientific/historical facts.",
    "",
    "## Review decisions and provisional boundaries",
    "",
    "- Q5 assesses application of the discovery-necessity test. Complete reasoning may leave object membership uncertain. The book does not provide a named-case yes/no key; yarn is not identical to the specific prehistoric spindle.",
    "- Q8 requires sound-based decoding, not only letters versus pictures. Chapter 8 pp. 111–112 supports this directly.",
    "- Q10 is a spoken adaptation of the exam's editing task. Manuscript citations supply conceptual context, not a canonical grammar/compression key. Meaning and usage judgments are provisional authored standards; any grammatical meaning-preserving reduction in spoken words can count, without a maximum-compression requirement. Current final proposal and cumulative learning evidence are different contracts.",
    "- Q12 applies general societal criteria to an institution. Qualified yes and qualified no can both meet all criteria; CAF practices in examples are illustrative inferences, not sourced institutional policy claims.",
    "- Q14 requires the assigned position and two distinct reasons. Alternative coherent reasons are welcome; two examples of the same reason are insufficient. More than two good reasons is acceptable.",
    "- Q15 separates manuscript claims about imagination/gravity from an authored philosophy-of-science synthesis. A complete answer distinguishes incomplete explanation from lack of value and develops one concrete usefulness argument. Evidence-and-limits is an optional strength, excluded from required live/cumulative assessment targets; its absence never makes an otherwise complete answer partial. Do not require every suggested keyword or a religious/philosophical profession of belief.",
    "- Q5/Q10 source material is projected into the actual tutor steering brief and each assessment target, so a learner may answer from the visible source without requiring the tutor to quote it into the transcript. Every Q10 criterion uses its own sentence and the same latest complete, non-withdrawn proposal. Proposal selection remains a later runtime implementation task.",
    "- Bill's review is required for official/course-calibrated marking claims, not for shipping explicitly provisional formative feedback. V1 has no numeric marks or pass/fail.",
    "",
    "## Shared attribution and closure rules",
    "",
    ...Object.entries(MAE386_ATTRIBUTION_RULES).map(([key, value]) => `- **${key}:** ${value}`),
    "",
    "## Inspected manuscript passages",
    "",
  ];
  for (const [id, source] of Object.entries(MANUSCRIPT_PASSAGES)) {
    lines.push(
      `### ${id}`,
      "",
      `${source.chapter}. **Printed pp. ${source.printedPages.join(", ")}**; one-based PDF viewer pages ${source.pdfPages.join(", ")}.`,
      "",
      source.establishes,
      "",
    );
  }
  for (const [index, question] of MAE386_RUBRICS.entries()) {
    const exam = MAE386_EXAM_SOURCE[question.id];
    lines.push(
      `## ${index + 1} of 8: Q${exam.number} — ${question.title}`,
      "",
      `**Mode:** ${question.mode}. **Exam printed/PDF pages:** ${exam.printedPages.join(", ")}.`,
      "",
      `**Adaptation:** ${question.adaptation}`,
      "",
      "### Original exam wording",
      "",
      exam.originalText,
      "",
    );
    for (const unit of question.units) {
      lines.push(`### ${unit.id}: ${unit.originalPart}`, "", `**Spoken prompt:** ${unit.prompt}`, "");
      if (unit.visibleSource) lines.push(`**Visible source material:** ${unit.visibleSource}`, "");
      lines.push("**Reference answer (authored):**", "", unit.referenceAnswer, "", "**Atomic evidence criteria:**", "");
      for (const criterion of unit.criteria) {
        lines.push(
          `- **${criterion.id}** [${criterion.optional ? "optional strength, not required for completeness" : "required"}; ${criterion.basis}; passages: ${criterion.sources.join(", ")}]: ${criterion.description}`,
        );
      }
      lines.push(
        "",
        `**Review boundary:** ${unit.review}`,
        "",
        "**Tutor conduct:**",
        "",
        ...Object.entries(unit.tutor).map(([key, value]) => `- **${key}:** ${value}`),
        "",
        "**Named learner examples:**",
        "",
      );
      for (const sample of unit.examples) {
        lines.push(`#### ${sample.name} [${sample.category}]`, "");
        sample.turns.forEach((turn, index) => lines.push(`${index + 1}. **${turn.speaker}:** ${turn.text}`));
        lines.push(
          "",
          `Expected criteria: ${Object.entries(sample.expected)
            .map(([id, state]) => `${id} = **${state}**`)
            .join("; ")}.`,
          "",
          `Learner evidence turn(s): ${sample.evidenceTurns.join(", ") || "none"}. ${sample.rationale}`,
          "",
        );
      }
    }
  }
  const output = await format(lines.join("\n"), { parser: "markdown", printWidth: 120 });
  const target = join(root, "docs/issue-76-rubric-review.md");
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) throw new Error("Rubric review copy is stale; rerun renderer.");
  } else writeFileSync(target, output);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
